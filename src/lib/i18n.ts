export function createTranslator(locale: Locale) {
  return (text: string) => locale === "en" ? (english[text] ?? text) : text;
}
export function countryDisplayName(code: string, locale: Locale): string {
  const country = countries.find(item => item.code === code);
  return country ? (locale === "en" ? country.nameEn : country.name) : code;
}
export function formatMonth(month: string, locale: Locale): string {
  const [year, value] = month.split("-").map(Number);
  if (!year || !value || value < 1 || value > 12) return month;
  return new Intl.DateTimeFormat(locale, { year: "numeric", month: "long", timeZone: "UTC" }).format(new Date(Date.UTC(year, value - 1, 1)));
}
export function formatHistoryDate(date: string, locale: Locale): string {
  const [year, month, day] = date.split("-").map(Number);
  if (!year || !month) return date;
  return new Intl.DateTimeFormat(locale, { year: "numeric", month: "long", ...(day ? { day: "numeric" as const } : {}), timeZone: "UTC" }).format(new Date(Date.UTC(year, month - 1, day || 1)));
}
